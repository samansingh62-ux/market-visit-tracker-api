// Market Visit phone app: keep the app shell available when the network drops.
// API calls are never cached here; the page keeps its own last-known data.
const SHELL = 'mvt-shell-v1';
const SHELL_FILES = ['/app', '/app/manifest.webmanifest', '/app/icon.svg'];

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(SHELL_FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  if (!SHELL_FILES.includes(url.pathname) && url.pathname !== '/app/') return;
  // Network first, so updates show immediately; fall back to the saved shell offline.
  e.respondWith(
    fetch(e.request)
      .then((res) => {
        const copy = res.clone();
        caches.open(SHELL).then((c) => c.put(e.request, copy));
        return res;
      })
      .catch(() => caches.match(e.request).then((r) => r || caches.match('/app')))
  );
});
